#!/usr/bin/env bash
# PreToolUse guard: exit 2 with a message when a tool call targets a protected file.
# Not a security boundary: owner review of the diff is the control.
# Keep this file LF (see .gitattributes).
command -v jq >/dev/null 2>&1 || exit 0
input=$(cat) || exit 0
fp=$(printf '%s' "$input" | jq -r '.tool_input.file_path // empty' 2>/dev/null) || exit 0
[ -n "$fp" ] || exit 0
rp=$(realpath -m -- "$fp" 2>/dev/null) || rp=$fp
for cand in "$fp" "$rp"; do
  case "$cand" in
    */Migrations/*.Designer.cs|*/Migrations/FactoryDbContextModelSnapshot.cs)
      echo "protect-files: $fp is generated by dotnet ef: ask the main session to run 'dotnet ef migrations add' instead." >&2
      exit 2
      ;;
    wwwroot/css/site.css|*/wwwroot/css/site.css)
      echo "protect-files: $fp is generated output: do not edit it by hand." >&2
      exit 2
      ;;
    .claude/settings.json|*/.claude/settings.json|\
    .claude/settings.local.json|*/.claude/settings.local.json|\
    .claude/hooks/protect-files.sh|*/.claude/hooks/protect-files.sh|\
    .mcp.json|*/.mcp.json)
      echo "protect-files: $fp is a protected file: ask the human; the owner applies this edit." >&2
      exit 2
      ;;
  esac
done
exit 0
